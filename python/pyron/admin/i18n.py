CATALOGS: dict[str, dict[str, str]] = {"en": EN, "es": ES, "pt": PT, "fr": FR}


class Translator:
    def __init__(self, lang: str) -> None:
        self.lang = lang if lang in CATALOGS else "en"
        self._table: Mapping[str, str] = CATALOGS[self.lang]

    def __call__(self, key: str, **kwargs: object) -> str:
        text = self._table.get(key) or EN.get(key, key)
        if kwargs:
            return text.format(**kwargs)
        return text


def parse_accept_language(header: str) -> str:
    for part in header.split(","):
        code = part.split(";")[0].strip().lower().replace("_", "-")
        short = code.split("-")[0]
        if short in CATALOGS:
            return short
    return "en"


def resolve_locale(cookie: str | None, accept: str | None) -> str:
    if cookie and cookie in CATALOGS:
        return cookie
    if accept:
        return parse_accept_language(accept)
    return "en"


def resolve_theme(cookie: str | None) -> str:
    if cookie in THEMES:
        return cookie
    return "system"
